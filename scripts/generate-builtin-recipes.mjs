import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const ids = ['chatgpt', 'claude', 'gemini', 'grok'];
const recipes = Object.fromEntries(ids.map(id => {
  const file = path.join(root, 'recipes', `${id}.recipe.json`);
  return [id, JSON.parse(fs.readFileSync(file, 'utf8'))];
}));
const output = `// Generated by scripts/generate-builtin-recipes.mjs. Do not edit directly.\n` +
  `import type { CustomRecipe } from '../types/recipe.js';\n\n` +
  `export const BUILTIN_RECIPES: Record<'chatgpt' | 'claude' | 'gemini' | 'grok', CustomRecipe> = ` +
  `${JSON.stringify(recipes, null, 2)} as Record<'chatgpt' | 'claude' | 'gemini' | 'grok', CustomRecipe>;\n`;
const target = path.join(root, 'src', 'shared', 'generated', 'builtinRecipes.ts');
if (process.argv.includes('--check')) {
  const existing = fs.existsSync(target)
    ? fs.readFileSync(target, 'utf8').replaceAll('\r\n', '\n')
    : null;
  if (existing !== output) {
    console.error('Built-in recipe output is stale. Run npm run generate:recipes.');
    process.exitCode = 1;
  }
} else {
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, output, 'utf8');
}
